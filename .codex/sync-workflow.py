#!/usr/bin/env python3
"""Generate source-reading Codex entrypoints; detect drift without executing sources."""

import argparse
import fcntl
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile
import tomllib


MANIFEST = ".codex/workflow-manifest.json"
BACKUP = ".codex/data/workflow-backup"


class ConflictError(ValueError):
    """A target was edited, removed from the catalog or points outside its scope."""


def digest(data):
    return hashlib.sha256(data).hexdigest()


def frontmatter(text):
    match = re.match(r"\A---\r?\n(.*?)\r?\n---(?:\r?\n|$)", text, re.S)
    return match.group(1) if match else ""


def field(text, name, default):
    """Read the simple text fields used by the project's source catalogs."""
    match = re.search(
        rf"^{re.escape(name)}:[ \t]*(.*?)(?=^[A-Za-z][A-Za-z0-9_-]*:[ \t]|\Z)",
        frontmatter(text), re.M | re.S,
    )
    if not match:
        return default
    value = match.group(1).strip()
    if value.startswith(("|", ">")):
        value = " ".join(line.strip() for line in value.splitlines()[1:])
    elif value.startswith('"'):
        try:
            value = json.loads(value)
        except json.JSONDecodeError:
            value = value.strip('"')
    elif value.startswith("'"):
        value = value.strip("'").replace("''", "'")
    return value or default


def wrapper(name, description, source, source_hash, kind):
    relative_base = str(Path(source).parent)
    # Codex discovery metadata has stricter limits than some source descriptions.
    description = description.replace("<", "").replace(">", "")
    if len(description) > 1024:
        description = description[:970].rsplit(" ", 1)[0] + " See source for detailed triggers."
    return (
        f"---\nname: {name}\ndescription: {json.dumps(description, ensure_ascii=False)}\n---\n\n"
        f"<!-- Generated by .codex/sync-workflow.py; source SHA-256: {source_hash} -->\n\n"
        f"# {name}\n\n"
        "Read `.codex/workflow.md` first for the Codex runtime adapter. Then read "
        f"`{source}` in full and follow its current {kind} instructions.\n\n"
        f"Resolve source-relative references and scripts from `{relative_base}/`, "
        "not from this generated entrypoint. Use the source project's templates and "
        "acceptance gates. Never substitute a stale global skill with the same name. "
        "Existing user authorization and session instructions take precedence.\n"
    )


def agent_content(root, target, source):
    existing = target.read_text() if target.exists() else ""
    settings = tomllib.loads(existing) if existing else {}
    settings["name"] = source.stem
    settings["description"] = field(source.read_text(), "description", source.stem)
    source_rel = source.relative_to(root).as_posix()
    settings["developer_instructions"] = (
        "Read `.codex/workflow.md` before starting. Then read "
        f"`{source_rel}` in full, including each skill named in its frontmatter "
        "from `.claude/skills/<name>/SKILL.md`. Follow the current source body "
        "and its linked references; resolve relative resources beside the source. "
        "Treat Claude model/tool names as source metadata and use this session's "
        "available tools. Preserve user authorization, ownership, blind-review "
        "requirements when independently dispatched, and receipt gates. "
        f"Source SHA-256: {digest(source.read_bytes())}."
    )
    # Preserve all existing runtime fields, including nested tables.
    instructions = json.dumps(settings["developer_instructions"], ensure_ascii=False)
    if existing:
        text = re.sub(
            r'^developer_instructions\s*=\s*(?:"""[\s\S]*?"""|\'\'\'[\s\S]*?\'\'\'|"(?:[^"\\]|\\.)*"|\'[^\']*\')',
            lambda _: "developer_instructions = " + instructions,
            existing,
            flags=re.M,
        )
        if "developer_instructions" not in tomllib.loads(text):
            text = "developer_instructions = " + instructions + "\n" + text
        for key in ("name", "description"):
            replacement = f"{key} = {json.dumps(settings[key], ensure_ascii=False)}"
            text = re.sub(
                rf'^{key}\s*=\s*(?:"""[\s\S]*?"""|\'\'\'[\s\S]*?\'\'\'|"(?:[^"\\]|\\.)*"|\'[^\']*\')',
                lambda _, value=replacement: value,
                text,
                flags=re.M,
            )
        tomllib.loads(text)
        return text
    return "\n".join(
        f"{key} = {json.dumps(settings[key], ensure_ascii=False)}"
        for key in ("name", "description", "developer_instructions")
    ) + "\n"


def guard_target(root, target):
    for part in [target, *target.parents]:
        if part == root:
            break
        if part.is_symlink():
            raise ConflictError(f"Symlink target requires explicit review: {target.relative_to(root)}")
    if not target.resolve().is_relative_to(root.resolve()):
        raise ConflictError("Target outside repository")


def catalog_allowlist(names, resources):
    ignore = ["# Generated catalog allowlist; preserve unrelated local skills/resources.", "skills/*"]
    ignore += [f"!skills/{name}/" for name in sorted(names)]
    ignore += ["skills/*/**", "!skills/*/SKILL.md"]
    for resource in sorted(resources):
        path = Path(resource)
        for parent in reversed(path.parents):
            if parent.as_posix() != ".":
                ignore.append(f"!{parent.as_posix()}/")
        ignore.append(f"!{resource}")
    return ("\n".join(dict.fromkeys(ignore)) + "\n").encode()


def catalog(root):
    entries = {}
    shared_resources = []
    sources = [
        (root / ".claude/skills", "*/SKILL.md", "skill"),
        (root / ".claude/commands", "*.md", "command"),
        (root / ".claude/agents", "*.md", "agent"),
    ]
    for base, pattern, kind in sources:
        for source in sorted(base.glob(pattern)):
            name = source.parent.name if kind == "skill" else source.stem
            if not re.fullmatch(r"[a-z0-9][a-z0-9-]{0,63}", name):
                raise ConflictError(f"Invalid catalog name: {name}")
            slug = "source-command-" + name if kind == "command" else name
            target_rel = (
                f".codex/agents/{name}.toml" if kind == "agent"
                else f".agents/skills/{slug}/SKILL.md"
            )
            target = root / target_rel
            guard_target(root, target)
            source_rel = source.relative_to(root).as_posix()
            source_hash = digest(source.read_bytes())
            if kind == "skill" and source.resolve() == target.resolve():
                # Some Claude skills already symlink to their Codex skill folder.
                text = source.read_text()
                shared_resources += [
                    p.relative_to(root / ".agents").as_posix()
                    for p in target.parent.rglob("*.md")
                    if p.name != "SKILL.md" and "__pycache__" not in p.parts
                ]
            elif kind == "agent":
                text = agent_content(root, target, source)
            else:
                text = wrapper(slug, field(source.read_text(), "description", f"Run /{name} using the current project workflow."), source_rel, source_hash, kind)
            entries[target_rel] = (text.encode(), {
                "source": source_rel,
                "source_index_path": source.resolve().relative_to(root).as_posix(),
                "source_sha256": source_hash,
                "target_sha256": digest(text.encode()),
            })
    names = {Path(name).parent.name for name in entries if name.startswith(".agents/skills/")}
    data = catalog_allowlist(names, shared_resources)
    source = ".codex/workflow.md"
    entries[".agents/.gitignore"] = (data, {
        "source": source, "source_index_path": source,
        "source_sha256": digest((root / source).read_bytes()), "target_sha256": digest(data),
    })
    return entries


def atomic_write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as stream:
        stream.write(data)
        temporary = Path(stream.name)
    temporary.replace(path)


def backup_originals(root, changes):
    backups = []
    for name in changes:
        target = root / name
        if target.exists():
            backup = root / BACKUP / name
            guard_target(root, backup)
            if backup.exists():
                raise ConflictError(f"Initial backup already exists: {name}")
            backups.append((backup, target.read_bytes()))
    for path, data in backups:
        atomic_write(path, data)


def sync(root, write=False, adopt=False):
    root = root.resolve()
    manifest_path = root / MANIFEST
    guard_target(root, manifest_path)
    old = json.loads(manifest_path.read_text()) if manifest_path.exists() else {}
    if adopt and old:
        raise ConflictError("Initial adoption is unavailable after a manifest exists")
    entries = catalog(root)
    if not entries:
        raise ConflictError("No Claude workflow sources found")
    previous = old.get("targets", {})
    changes, conflicts = [], []
    for target_rel, (data, record) in entries.items():
        target = root / target_rel
        current = target.read_bytes() if target.exists() else None
        if current != data or previous.get(target_rel) != record:
            changes.append(target_rel)
        saved = previous.get(target_rel)
        if current is not None and current != data:
            if saved and digest(current) != saved["target_sha256"]:
                conflicts.append(f"Edited target: {target_rel}")
            elif not saved and not adopt:
                conflicts.append(f"Unmanaged target: {target_rel}; review initial adoption")
    for removed in previous.keys() - entries.keys():
        conflicts.append(f"Source removed; adapter retained for review: {removed}")
    manifest = {
        "version": 1,
        "adapter_sha256": digest((root / ".codex/workflow.md").read_bytes()),
        "targets": {name: record for name, (_, record) in entries.items()},
    }
    manifest_data = (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode()
    if not manifest_path.exists() or manifest_path.read_bytes() != manifest_data:
        changes.append(MANIFEST)
    if not write:
        return conflicts + changes
    if conflicts:
        raise ConflictError("\n".join(conflicts))
    if adopt:
        backup_originals(root, changes)
    for name in changes:
        data = manifest_data if name == MANIFEST else entries[name][0]
        if not (root / name).exists() or (root / name).read_bytes() != data:
            atomic_write(root / name, data)
    return changes


def check_staged(root):
    """Check actual index bytes, including sources reached through directory symlinks."""
    def read_index(name):
        result = subprocess.run(
            ["git", "show", f":{name}"], cwd=root, capture_output=True, timeout=10, check=False
        )
        return result.stdout if result.returncode == 0 else None

    data = read_index(MANIFEST)
    if data is None:
        return ["Workflow manifest is not staged/tracked"]
    staged = json.loads(data)
    problems = []
    for name, record in staged["targets"].items():
        for path, expected in (
            (record.get("source_index_path", record["source"]), record["source_sha256"]),
            (name, record["target_sha256"]),
        ):
            content = read_index(path)
            if content is None or digest(content) != expected:
                problems.append(f"Index differs from manifest: {path}")
    adapter = read_index(".codex/workflow.md")
    if adapter is None or digest(adapter) != staged["adapter_sha256"]:
        problems.append("Index differs from manifest: .codex/workflow.md")
    return problems


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    parser.add_argument("--adopt-existing", action="store_true")
    parser.add_argument("--staged", action="store_true", help="also verify actual Git index bytes")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    try:
        if args.write:
            lock = root / ".codex/data/workflow-sync.lock"
            guard_target(root, lock)
            lock.parent.mkdir(parents=True, exist_ok=True)
            with lock.open("a") as stream:
                fcntl.flock(stream, fcntl.LOCK_EX | fcntl.LOCK_NB)
                changes = sync(root, write=True, adopt=args.adopt_existing)
        else:
            changes = sync(root)
            if args.staged:
                changes += check_staged(root)
    except (OSError, ValueError, KeyError, subprocess.TimeoutExpired) as error:
        print(f"workflow-sync: {error}")
        return 2
    print(f"workflow-sync: {'updated' if args.write else 'drift'}={len(changes)}")
    if not args.write:
        for name in changes:
            print("  " + name)
    return 1 if changes and args.check else 0


if __name__ == "__main__":
    raise SystemExit(main())
